-- =====================================================================
-- Conecta Alimento - script manual para o Oracle da FIAP (SQL Developer)
-- A API já cria as tabelas sozinha na primeira execução; use este script
-- apenas para recriar o banco do zero. Execute com F5 (Executar Script).
-- ATENÇÃO: os DROPs apagam todos os dados das tabelas T_CA_*.
-- =====================================================================

BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('T_CA_RETIRADA','T_CA_SOLICITACAO','T_CA_ALIMENTO',
                                   'T_CA_INSTITUICAO','T_CA_ESTABELECIMENTO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/


CREATE TABLE T_CA_ESTABELECIMENTO (
    ID_ESTABELECIMENTO  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NM_ESTABELECIMENTO  VARCHAR2(120) NOT NULL,
    NM_RESPONSAVEL      VARCHAR2(100) NOT NULL,
    DS_EMAIL            VARCHAR2(120) NOT NULL,
    DS_SENHA            VARCHAR2(64)  NOT NULL,
    NR_TELEFONE         VARCHAR2(11)  NOT NULL,
    NR_CNPJ             VARCHAR2(14)  NOT NULL,
    TP_ESTABELECIMENTO  VARCHAR2(20)  NOT NULL,
    DS_LOGRADOURO       VARCHAR2(120) NOT NULL,
    NR_LOGRADOURO       VARCHAR2(10)  NOT NULL,
    NM_BAIRRO           VARCHAR2(20)  NOT NULL,
    NR_CEP              VARCHAR2(8)   NOT NULL,
    NR_LATITUDE         NUMBER(9,6)   NOT NULL,
    NR_LONGITUDE        NUMBER(9,6)   NOT NULL,
    DT_CADASTRO         TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CA_ESTABELECIMENTO PRIMARY KEY (ID_ESTABELECIMENTO),
    CONSTRAINT UN_CA_ESTAB_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT UN_CA_ESTAB_CNPJ UNIQUE (NR_CNPJ),
    CONSTRAINT CK_CA_ESTAB_TIPO CHECK (TP_ESTABELECIMENTO IN ('PADARIA','MERCADO','RESTAURANTE','HORTIFRUTI','OUTRO')),
    CONSTRAINT CK_CA_ESTAB_BAIRRO CHECK (NM_BAIRRO IN ('BOM_RETIRO','PARI','BRAS'))
);

CREATE TABLE T_CA_INSTITUICAO (
    ID_INSTITUICAO      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NM_INSTITUICAO      VARCHAR2(120) NOT NULL,
    NM_RESPONSAVEL      VARCHAR2(100) NOT NULL,
    DS_EMAIL            VARCHAR2(120) NOT NULL,
    DS_SENHA            VARCHAR2(64)  NOT NULL,
    NR_TELEFONE         VARCHAR2(11)  NOT NULL,
    TP_INSTITUICAO      VARCHAR2(25)  NOT NULL,
    QT_CAPACIDADE       NUMBER(6)     NOT NULL,
    DS_LOGRADOURO       VARCHAR2(120) NOT NULL,
    NR_LOGRADOURO       VARCHAR2(10)  NOT NULL,
    NM_BAIRRO           VARCHAR2(20)  NOT NULL,
    NR_CEP              VARCHAR2(8)   NOT NULL,
    NR_LATITUDE         NUMBER(9,6)   NOT NULL,
    NR_LONGITUDE        NUMBER(9,6)   NOT NULL,
    DT_CADASTRO         TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CA_INSTITUICAO PRIMARY KEY (ID_INSTITUICAO),
    CONSTRAINT UN_CA_INST_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_CA_INST_TIPO CHECK (TP_INSTITUICAO IN ('ONG','COZINHA_COMUNITARIA','ABRIGO','PROJETO_SOCIAL','OUTRA')),
    CONSTRAINT CK_CA_INST_BAIRRO CHECK (NM_BAIRRO IN ('BOM_RETIRO','PARI','BRAS')),
    CONSTRAINT CK_CA_INST_CAPACIDADE CHECK (QT_CAPACIDADE > 0)
);

CREATE TABLE T_CA_ALIMENTO (
    ID_ALIMENTO         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTABELECIMENTO  NUMBER(10)    NOT NULL,
    NM_ALIMENTO         VARCHAR2(120) NOT NULL,
    TP_ALIMENTO         VARCHAR2(15)  NOT NULL,
    DS_CATEGORIA        VARCHAR2(20)  NOT NULL,
    QT_ALIMENTO         NUMBER(10,2)  NOT NULL,
    DS_UNIDADE          VARCHAR2(10)  NOT NULL,
    DT_VALIDADE         DATE          NOT NULL,
    DT_INICIO_RETIRADA  TIMESTAMP     NOT NULL,
    DT_FIM_RETIRADA     TIMESTAMP     NOT NULL,
    DS_ARMAZENAMENTO    VARCHAR2(25)  NOT NULL,
    ST_EMBALAGEM_INTEGRA CHAR(1)      NOT NULL,
    DS_LOTE             VARCHAR2(30),
    DS_OBSERVACAO       VARCHAR2(255),
    ST_DECLARACAO       CHAR(1)       NOT NULL,
    ST_ALIMENTO         VARCHAR2(20)  NOT NULL,
    DT_CADASTRO         TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CA_ALIMENTO PRIMARY KEY (ID_ALIMENTO),
    CONSTRAINT FK_CA_ALIM_ESTAB FOREIGN KEY (ID_ESTABELECIMENTO) REFERENCES T_CA_ESTABELECIMENTO (ID_ESTABELECIMENTO),
    CONSTRAINT CK_CA_ALIM_TIPO CHECK (TP_ALIMENTO IN ('PERECIVEL','NAO_PERECIVEL')),
    CONSTRAINT CK_CA_ALIM_CATEGORIA CHECK (DS_CATEGORIA IN ('PANIFICACAO','HORTIFRUTI','LATICINIOS','CARNES','REFEICAO_PRONTA','MERCEARIA','BEBIDAS')),
    CONSTRAINT CK_CA_ALIM_QTD CHECK (QT_ALIMENTO > 0),
    CONSTRAINT CK_CA_ALIM_UNIDADE CHECK (DS_UNIDADE IN ('KG','UNIDADE','LITRO','PACOTE')),
    CONSTRAINT CK_CA_ALIM_ARMAZ CHECK (DS_ARMAZENAMENTO IN ('TEMPERATURA_AMBIENTE','REFRIGERADO','CONGELADO')),
    CONSTRAINT CK_CA_ALIM_EMBALAGEM CHECK (ST_EMBALAGEM_INTEGRA IN ('S','N')),
    CONSTRAINT CK_CA_ALIM_DECLARACAO CHECK (ST_DECLARACAO IN ('S','N')),
    CONSTRAINT CK_CA_ALIM_STATUS CHECK (ST_ALIMENTO IN ('DISPONIVEL','SOLICITADO','RESERVADO','RETIRADA_AGENDADA','CONCLUIDO','REMOVIDO','EXPIRADO'))
);

CREATE TABLE T_CA_SOLICITACAO (
    ID_SOLICITACAO      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_ALIMENTO         NUMBER(10)    NOT NULL,
    ID_INSTITUICAO      NUMBER(10)    NOT NULL,
    QT_SOLICITADA       NUMBER(10,2)  NOT NULL,
    ST_SOLICITACAO      VARCHAR2(15)  NOT NULL,
    DS_MOTIVO           VARCHAR2(255),
    DT_RESPOSTA         TIMESTAMP,
    DT_CADASTRO         TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CA_SOLICITACAO PRIMARY KEY (ID_SOLICITACAO),
    CONSTRAINT FK_CA_SOLIC_ALIMENTO FOREIGN KEY (ID_ALIMENTO) REFERENCES T_CA_ALIMENTO (ID_ALIMENTO),
    CONSTRAINT FK_CA_SOLIC_INST FOREIGN KEY (ID_INSTITUICAO) REFERENCES T_CA_INSTITUICAO (ID_INSTITUICAO),
    CONSTRAINT CK_CA_SOLIC_QTD CHECK (QT_SOLICITADA > 0),
    CONSTRAINT CK_CA_SOLIC_STATUS CHECK (ST_SOLICITACAO IN ('PENDENTE','ACEITA','RECUSADA','NAO_ATENDIDA','CANCELADA','AGENDADA','CONCLUIDA'))
);

CREATE TABLE T_CA_RETIRADA (
    ID_RETIRADA         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_SOLICITACAO      NUMBER(10)    NOT NULL,
    DT_AGENDADA         TIMESTAMP     NOT NULL,
    ST_ENTREGA          CHAR(1)       NOT NULL,
    DT_ENTREGA          TIMESTAMP,
    QT_ENTREGUE         NUMBER(10,2),
    ST_RECEBIMENTO      CHAR(1)       NOT NULL,
    DT_RECEBIMENTO      TIMESTAMP,
    QT_RECEBIDA         NUMBER(10,2),
    DS_OBSERVACAO       VARCHAR2(255),
    DT_CADASTRO         TIMESTAMP     NOT NULL,
    CONSTRAINT PK_CA_RETIRADA PRIMARY KEY (ID_RETIRADA),
    CONSTRAINT FK_CA_RETIR_SOLIC FOREIGN KEY (ID_SOLICITACAO) REFERENCES T_CA_SOLICITACAO (ID_SOLICITACAO),
    CONSTRAINT UN_CA_RETIR_SOLIC UNIQUE (ID_SOLICITACAO),
    CONSTRAINT CK_CA_RETIR_ENTREGA CHECK (ST_ENTREGA IN ('S','N')),
    CONSTRAINT CK_CA_RETIR_RECEB CHECK (ST_RECEBIMENTO IN ('S','N'))
);

-- Consultas de conferência
SELECT table_name FROM user_tables WHERE table_name LIKE 'T_CA_%' ORDER BY table_name;
